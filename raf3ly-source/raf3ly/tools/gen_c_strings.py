#!/usr/bin/env python3
"""Generates app/src/native/strings_enc.h: XOR-encrypted C string constants so that
`strings libnd.so` shows none of the paths / markers used by the guard."""
import os, random
NAMES = {
    "S_CLASSES": b"classes.dex",
    "S_BASEAPK": b"base.apk",
    "S_MAPS": b"/proc/self/maps",
    "S_STATUS": b"/proc/self/status",
    "S_KILLER": b"libkiller",
    "S_FRIDA": b"frida",
    "S_XPOSED": b"libxposed",
    "S_LSPD": b"lspd",
    "S_SUBSTRATE": b"substrate",
    "S_GUM": b"gum-js",
}
random.seed(os.urandom(16))
out = ["/* generated by tools/gen_c_strings.py - do not edit */", "#ifndef RAF3LY_STRINGS_H", "#define RAF3LY_STRINGS_H", ""]
for name, val in NAMES.items():
    key = random.getrandbits(8)
    enc = [b ^ key for b in val]
    out.append("#define %s_KEY 0x%02X" % (name, key))
    out.append("static const unsigned char %s_A[] = {%s};" % (name, ",".join(str(b) for b in enc)))
    out.append("")
out += ["#endif", ""]
open("/home/user/raf3ly/app/src/native/strings_enc.h", "w").write("\n".join(out))
print("generated strings_enc.h")
